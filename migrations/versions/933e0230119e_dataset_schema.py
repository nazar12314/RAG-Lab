def _grant_retriever_access() -> None:
    # Retrievers and agent tools run as this read-only role; it has no access to `eval`,
    # so gold labels cannot leak into retrieval even through a bug.
    op.execute(
        f"""
        DO $$ BEGIN
            IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '{RETRIEVER_ROLE}') THEN
                CREATE ROLE {RETRIEVER_ROLE} NOLOGIN;
            END IF;
        END $$;
        """
    )
    op.execute(f"GRANT {RETRIEVER_ROLE} TO CURRENT_USER")
    for schema in RETRIEVER_SCHEMAS:
        op.execute(f"GRANT USAGE ON SCHEMA {schema} TO {RETRIEVER_ROLE}")
        op.execute(f"GRANT SELECT ON ALL TABLES IN SCHEMA {schema} TO {RETRIEVER_ROLE}")
        op.execute(
            f"ALTER DEFAULT PRIVILEGES IN SCHEMA {schema} GRANT SELECT ON TABLES TO {RETRIEVER_ROLE}"
        )


